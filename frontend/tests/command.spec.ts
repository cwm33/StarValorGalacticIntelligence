import { test, expect } from '@playwright/test'
import { execFileSync } from 'node:child_process'
import { mkdtempSync, rmSync, readFileSync, mkdirSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { createHash } from 'node:crypto'
import { join } from 'node:path'

let directory: string, fixture: string, inputHash: string
test.beforeAll(() => {
  directory = mkdtempSync(join(tmpdir(), 'galactic-synthetic-'))
  fixture = join(directory, 'SaveGameData_99.dat')
  execFileSync(process.env.PYTHON ?? 'python3', ['../tests/api_smoke.py', '--fixture', fixture])
  inputHash = createHash('sha256').update(readFileSync(fixture)).digest('hex')
})
test.afterAll(() => rmSync(directory, { recursive: true, force: true }))

